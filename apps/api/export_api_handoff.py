"""Export checked API payloads, OpenAPI, and TypeScript types from the real app."""

import json
import re
from pathlib import Path

from fastapi.testclient import TestClient

from app.contracts import AnalysisExample, AnalysisResponse, FinancialSummary
from app.decision import financial_result, planting_advice, water_risk
from app.main import create_app
from app.service import default_request

ROOT = Path(__file__).resolve().parents[2]


def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n", encoding="utf-8", newline="\n")


def identifier(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def ts_type(schema):
    if "$ref" in schema:
        return identifier(schema["$ref"].split("/")[-1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key, operator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + operator.join(ts_type(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        if properties:
            required = set(schema.get("required", []))
            fields = [f"  {json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};" for key, value in properties.items()]
            return "{\n" + "\n".join(fields) + "\n}"
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def export_types(schema):
    lines = ["// Generated by apps/api/export_api_handoff.py from FastAPI OpenAPI. Do not edit by hand.", ""]
    paths = schema["paths"]
    aliases = {"AnalyzePayload": paths["/api/v1/analyze"]["post"]["requestBody"]["content"]["application/json"]["schema"]}
    for name, path, status in (("AnalyzeResult", "/api/v1/analyze", "200"), ("OptionsResult", "/api/v1/options", "200"),
                               ("ReadyResult", "/ready", "200"), ("AnalysisExampleResult", "/api/v1/examples/analysis", "200"),
                               ("ApiErrorResult", "/api/v1/analyze", "422")):
        method = "post" if path.endswith("analyze") else "get"
        aliases[name] = paths[path][method]["responses"][status]["content"]["application/json"]["schema"]
    definitions = schema["components"]["schemas"]
    reachable = set()
    def visit(node):
        if isinstance(node, dict):
            if "$ref" in node:
                name = node["$ref"].split("/")[-1]
                if name not in reachable:
                    reachable.add(name)
                    visit(definitions[name])
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)
    for definition in aliases.values():
        visit(definition)
    for name in sorted(reachable):
        lines.append(f"export type {identifier(name)} = {ts_type(definitions[name])};\n")
    lines.extend(f"export type {name} = {ts_type(definition)};" for name, definition in aliases.items())
    path = ROOT / "shared/src/types/clovis.ts"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "apps/web/lib/field-shift-api.types.ts").write_text(
        '// Canonical contracts are exported by @spaceapps/shared.\nexport type * from "@spaceapps/shared";\n', encoding="utf-8", newline="\n")


def main():
    app = create_app()
    examples = ROOT / "examples/api"
    payload = default_request().model_dump(mode="json")
    compact = {**payload, "include_daily_trajectory": False}
    with TestClient(app) as client:
        readiness = client.get("/ready")
        if readiness.status_code != 200:
            raise RuntimeError("Real model/weather artifacts must load before exporting computed examples")
        response = client.post("/api/v1/analyze", json=payload)
        response.raise_for_status()
        result = AnalysisResponse.model_validate(response.json())
        example = result.model_copy(update={"execution_mode": "example"})
        pair = AnalysisExample(request=default_request(), response=example)
        save(examples / "analyze.request.json", payload)
        save(examples / "analyze.response.json", result.model_dump(mode="json"))
        save(examples / "analysis.example.json", pair.model_dump(mode="json"))
        save(examples / "analyze.compact.request.json", compact)
        compact_result = result.model_copy(deep=True)
        compact_result.request.include_daily_trajectory = False
        for case in compact_result.scenarios:
            case.daily_trajectory = None
        save(examples / "analyze.compact.response.json", compact_result.model_dump(mode="json"))
        save(examples / "options.response.json", client.get("/api/v1/options").json())
        save(examples / "ready.response.json", readiness.json())
        invalid = {**compact, "area_ha": -1}
        save(examples / "validation-error.request.json", invalid)
        invalid_response = client.post("/api/v1/analyze", json=invalid)
        assert invalid_response.status_code == 422
        save(examples / "validation-error.response.json", invalid_response.json())
        app.state.analysis_slots.acquire()
        try:
            busy = client.post("/api/v1/analyze", json=compact)
            assert busy.status_code == 429
            save(examples / "busy.response.json", busy.json())
        finally:
            app.state.analysis_slots.release()
        revenue_payload = {**compact, "economics": {**compact["economics"], "net_cover_revenue_usd_ha": 100.0}}
        revenue_response = client.post("/api/v1/analyze", json=revenue_payload)
        revenue_response.raise_for_status()
        save(examples / "analyze.with-revenue.request.json", revenue_payload)
        save(examples / "analyze.with-revenue.response.json", revenue_response.json())
        review_payload = {**compact, "economics": {**compact["economics"], "net_cover_revenue_usd_ha": 85.0}}
        review_response = client.post("/api/v1/analyze", json=review_payload)
        review_response.raise_for_status()
        fixtures = {"do-not-plant": compact_result, "plant": AnalysisResponse.model_validate(revenue_response.json()),
                    "review": AnalysisResponse.model_validate(review_response.json())}
        missing = compact_result.model_copy(deep=True)
        missing.execution_mode = "example"
        missing.request_id = "synthetic-missing-baseline-ui-fixture"
        for case in missing.scenarios:
            case.moisture.relative_final_7_day_difference = None
            case.finances = financial_result(None, missing.request.economics, missing.request.area_ha)
            case.water_risk = water_risk(None, missing.request.risk_rules)
            case.quality.flags.append("synthetic_missing_baseline_ui_fixture")
        missing.financial_summary = FinancialSummary(minimum_incremental_net_benefit_usd_ha=None,
            maximum_incremental_net_benefit_usd_ha=None, cases_with_positive_incremental_benefit=0, calculated_cases=0, case_count=3)
        missing.recommendation = planting_advice(missing.scenarios, ["synthetic_missing_baseline_ui_fixture"])
        fixtures["insufficient-evidence"] = missing
        for name, fixture in fixtures.items():
            fixture = fixture.model_copy(deep=True)
            fixture.execution_mode = "example"
            save(ROOT / f"shared/payloads/clovis-analysis-{name}.json", fixture.model_dump(mode="json"))
        save(ROOT / "shared/payloads/clovis-analysis-request.json", compact)
        save(examples / "verification.json", {"computed_response_status": response.status_code,
            "analysis_duration_ms": float(response.headers["X-Process-Time-Ms"]),
            "model_sha256": result.model.artifact_sha256, "scenario_count": len(result.scenarios),
            "trajectory_points": sum(len(case.daily_trajectory or []) for case in result.scenarios),
            "recommendation": result.recommendation.decision, "initial_moisture_semantics": "daily_average"})
    with TestClient(create_app(lambda: None)) as client:
        save(examples / "unavailable.response.json", client.post("/api/v1/analyze", json=compact).json())
        save(examples / "ready.unavailable.response.json", client.get("/ready").json())
    schema = app.openapi()
    save(ROOT / "docs/openapi.json", schema)
    export_types(schema)
    print(json.dumps({"examples": str(examples), "openapi": str(ROOT / "docs/openapi.json"),
                      "scenario_count": len(result.scenarios), "analysis_duration_ms": response.headers["X-Process-Time-Ms"],
                      "recommendation": result.recommendation.decision}, indent=2))


if __name__ == "__main__":
    main()
