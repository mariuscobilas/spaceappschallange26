import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";

test("Explore switches between Conditions and historical research inside Map options", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  const toolbar = page.locator('header[aria-label="Map toolbar"]');
  await expect(toolbar.getByLabel("Field or location")).toHaveCount(0);
  await expect(toolbar.getByLabel("Cash crop")).toHaveCount(0);
  await expect(toolbar.getByRole("button", { name: "Map options", exact: true })).toBeVisible();
  await expect(toolbar.getByLabel("Observation period")).toHaveCount(0);
  await expect(toolbar.getByRole("button", { name: "Draw boundary" })).toHaveCount(0);
  await expect(toolbar.getByRole("button", { name: "Selected location details" })).toHaveCount(0);
  await page.getByRole("button", { name: "Map options", exact: true }).click();
  const options = page.getByRole("dialog", { name: "Map options", exact: true });
  await expect(options.getByLabel("Data view", { exact: true })).toHaveValue("conditions");
  await expect(options.getByLabel("Research crop", { exact: true })).toHaveCount(0);
  await options.getByLabel("Observation period").selectOption("past");
  await expect(options.getByLabel("Observation date", { exact: true })).toBeVisible();
  await options.getByLabel("Data view", { exact: true }).selectOption("research");
  await expect(page).toHaveURL(/\?view=research/);
  await page.getByRole("button", { name: "Map options", exact: true }).click();
  const researchOptions = page.getByRole("dialog", { name: "Map options", exact: true });
  await expect(researchOptions.getByLabel("Research crop", { exact: true })).toHaveValue("corn");
  await expect(researchOptions.getByLabel("Study period", { exact: true })).toHaveValue("2019-2020");
  await expect(researchOptions.getByLabel("County", { exact: true })).toBeVisible();
  await expect(researchOptions.getByLabel("Atlas layer", { exact: true })).toHaveCount(0);
  await expect(researchOptions.getByLabel("Management scenario", { exact: true })).toHaveCount(0);
  await researchOptions.getByLabel("Research crop", { exact: true }).selectOption("soybeans");
  await researchOptions.getByLabel("Study period", { exact: true }).selectOption("2020");
  await expect(page).toHaveURL(/crop=soybeans.*period=2020/);
  await page.keyboard.press("Escape");
  await expect(page.getByLabel("Historical research map legend", { exact: true })).toContainText("Historical research · Soybeans · 2020");

  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Map options", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Map options", exact: true }).getByLabel("Research crop", { exact: true })).toHaveValue("soybeans");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("Historical research selects a county aggregate without changing field context", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.route("https://tiles.openfreemap.org/**", (route) => route.abort());
  const example = JSON.parse(readFileSync("../../shared/payloads/field-conditions-available.json", "utf8"));
  await page.route("**/api/v1/field-conditions?**", (route) => {
    const query = new URL(route.request().url()).searchParams;
    const response = structuredClone(example);
    response.sample = { latitude: Number(query.get("latitude")), longitude: Number(query.get("longitude")) };
    response.requestedDate = query.get("as_of");
    return route.fulfill({ json: response });
  });
  await page.goto("/?view=research&crop=corn&period=2019-2020");
  await expect.poll(() => page.evaluate(() => !!JSON.parse(localStorage.getItem("meridian.map-settings.v3") ?? "{}").selection)).toBe(true);
  const fieldContext = await page.evaluate(() => JSON.parse(localStorage.getItem("meridian.map-settings.v3") ?? "{}").selection);
  const canvas = page.locator(".map-canvas");
  await page.getByRole("button", { name: "Map options", exact: true }).click();
  await page.getByRole("dialog", { name: "Map options", exact: true }).getByRole("button", { name: "Reset study view", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(canvas).toHaveAttribute("data-regional-county-count", "1");
  await expect(canvas).toHaveAttribute("data-regional-ready", "true");
  await expect(canvas).toHaveAttribute("data-regional-crop", "corn");
  await expect(canvas).toHaveAttribute("data-regional-period", "2019-2020");
  await expect(async () => {
    const bounds = await canvas.boundingBox();
    if (!bounds) throw new Error("Research map is not visible");
    await page.mouse.click(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await expect(page.getByRole("complementary", { name: "Region overview" })).toBeVisible();
  }).toPass({ timeout: 15000 });
  const panel = page.getByRole("complementary", { name: "Region overview" });
  await expect(panel.getByRole("region", { name: "Published county estimate details", exact: true })).toContainText("Estimated yield difference");
  await expect(panel).toContainText("Adams, IL");
  await expect(panel).toContainText("−5.38%");
  await expect(panel).toContainText("155");
  await expect(panel).toContainText("not a county-wide measured yield, current field forecast, or farm prediction");
  await expect(page.getByRole("region", { name: "Historical research map legend", exact: true })).toContainText("Historical research");
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("meridian.map-settings.v3") ?? "{}").selection)).toEqual(fieldContext);
  const mapBounds = await canvas.boundingBox();
  const panelBounds = await panel.boundingBox();
  expect(mapBounds!.x + mapBounds!.width).toBeLessThanOrEqual(panelBounds!.x + 1);
  await page.getByRole("button", { name: "Zoom in", exact: true }).click();
  await expect(panel).toBeVisible();
  await expect(page).toHaveURL(/county=17001/);
  await page.setViewportSize({ width: 390, height: 844 });
  const mobile = page.getByRole("dialog", { name: "Historical research information", exact: true });
  await expect(mobile).toBeVisible();
  await expect(mobile.getByRole("region", { name: "Published county estimate details", exact: true })).toContainText("Adams, IL");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await expect(mobile.getByRole("button", { name: "Inspect field here", exact: true })).toHaveCount(0);
});

test("phone navigation keeps research inside Explore rather than a primary destination", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByRole("button", { name: "Toggle navigation", exact: true }).click();
  const navigation = page.getByRole("navigation", { name: "Main navigation", exact: true });
  await expect(navigation.getByRole("link", { name: "Regional Atlas", exact: true })).toHaveCount(0);
  await navigation.getByRole("link", { name: "Explore", exact: true }).click();
  await page.getByRole("button", { name: "Map options", exact: true }).click();
  const options = page.getByRole("dialog", { name: "Map options", exact: true });
  await options.getByLabel("Data view", { exact: true }).selectOption("research");
  await expect(page).toHaveURL(/\?view=research/);
  await expect(page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("link", { name: "Explore", exact: true })).toHaveAttribute("aria-current", "page");
  await options.getByLabel("Data view", { exact: true }).selectOption("conditions");
  await expect(page).toHaveURL(/\/$/);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("meridian.map-settings.v3") ?? "{}").mode)).toBe("field");
});

test("phone My fields panel closes before placing and saving a point", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.route("https://tiles.openfreemap.org/**", (route) => route.abort());
  await page.goto("/fields");
  await page.getByRole("button", { name: /My fields \(0\)/ }).click();
  const panel = page.getByRole("dialog", { name: "My fields", exact: true });
  await expect(panel).toBeVisible();
  await panel.getByRole("button", { name: "Select point", exact: true }).click();
  await expect(panel).toBeHidden();
  await expect(page.getByText("Click the map to place a field point.")).toBeVisible();
  const canvas = page.locator(".map-canvas");
  const bounds = await canvas.boundingBox();
  if (!bounds) throw new Error("Map canvas is not visible");
  await page.mouse.click(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5);
  const details = page.getByRole("dialog", { name: "Field details", exact: true });
  await expect(details).toBeVisible();
  await details.getByLabel("Field name", { exact: true }).fill("Mobile point");
  await details.getByRole("button", { name: "Save field", exact: true }).click();
  await expect(details).toBeHidden();
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("meridian.fields.v1") ?? "{}").fields?.length)).toBe(1);
  await page.getByRole("button", { name: /My fields \(1\)/ }).click();
  await expect(page.getByRole("dialog", { name: "My fields", exact: true })).toContainText("Mobile point");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
